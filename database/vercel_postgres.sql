CREATE TABLE IF NOT EXISTS comments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_id VARCHAR(40) NOT NULL,
  visitor_id UUID NOT NULL,
  name VARCHAR(60) NOT NULL,
  comment_text VARCHAR(1000) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_comments_content_created
  ON comments (content_id, created_at, id);

CREATE TABLE IF NOT EXISTS reactions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_id VARCHAR(40) NOT NULL,
  visitor_id UUID NOT NULL,
  reaction_type VARCHAR(16) NOT NULL
    CHECK (reaction_type IN ('like', 'love', 'care', 'haha', 'wow', 'sad', 'angry')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_reactions_content_visitor UNIQUE (content_id, visitor_id)
);

CREATE INDEX IF NOT EXISTS idx_reactions_content ON reactions (content_id);

CREATE TABLE IF NOT EXISTS shares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  content_id VARCHAR(40) NOT NULL,
  visitor_id UUID NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_shares_content_created
  ON shares (content_id, created_at);
